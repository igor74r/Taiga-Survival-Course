const assert = require('node:assert/strict');
const { normalize, VERSION } = require('../GAME_TAIGA_IDLE/src/services/save-service.js');
const fresh = () => ({version:1,day:1,hour:7,last:1000,hp:100,hunger:80,thirst:80,energy:90,warmth:80,morale:70,wood:4,branch:5,stone:1,berry:2,mushroom:0,water:2,fish:0,metal:0,cloth:0,food:1,knife:0,base:0,fire:0,fireMinutes:0,torch:0,story:0,jobs:[],crafted:[],known:['camp','river','forest'],log:['start'],tab:'camp'});
const now=10000;
const empty=normalize(null,fresh,now);
assert.equal(empty.version,VERSION);
assert.equal(empty.day,1);
const migrated=normalize({version:1,day:4,hour:27,hp:140,hunger:-5,wood:12,fire:1,fireMinutes:40,known:['camp','river','bog'],tab:'invalid',last:9000,jobs:[{name:'Рубить сухостой',left:30,reward:{wood:3,other:500}}]},fresh,now);
assert.equal(migrated.version,VERSION);
assert.equal(migrated.day,4);
assert.equal(migrated.hour,23);
assert.equal(migrated.hp,100);
assert.equal(migrated.hunger,0);
assert.equal(migrated.fire,1);
assert.deepEqual(migrated.known,['camp','river']);
assert.equal(migrated.tab,'camp');
assert.deepEqual(migrated.jobs,[{name:'Рубить сухостой',left:30,reward:{wood:3},paid:false}]);
const safe=normalize({version:2,last:now+600000,torch:'bad',jobs:[{name:'unknown',left:2,reward:{wood:1}},{name:'Собирать ягоды',left:99999,reward:{berry:2}}],log:[null,'ok']},fresh,now);
assert.equal(safe.last,now);
assert.equal(safe.torch,0);
assert.equal(safe.jobs.length,1);
assert.equal(safe.jobs[0].left,1440);
assert.deepEqual(safe.log,['ok']);
console.log('TAIGA save service tests passed.');
